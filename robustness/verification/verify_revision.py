PARTIES='ABC'; LETTERS='ZXD'; ONE=('','','')
PERMS=list(itertools.permutations(range(3)))
def require(value: bool, message: str) -> None:
    if not value: raise ValueError(message)
def reduce_local(st: str) -> str:
    out=[]
    for x in st:
        if out and out[-1]==x: out.pop()
        else: out.append(x)
    return ''.join(out)
def mul(u,v): return tuple(reduce_local(a+b) for a,b in zip(u,v))
def adj(u): return tuple(a[::-1] for a in u)
def obs(p,l): return tuple(l if q==p else '' for q in PARTIES)
def degree(w): return sum(map(len,w))
def word_name(w): return '*'.join(p+x for p,z in zip(PARTIES,w) for x in z) or 'I'
def permute(w,p):
    out=['']*3
    for old,new in enumerate(p): out[new]=w[old]
    return tuple(out)
def orbit(w):
    return min((v for p in PERMS for v in (permute(w,p),adj(permute(w,p)))),key=lambda z:(degree(z),word_name(z)))
def word_basis():
    B=[ONE]+[obs(p,l) for p in PARTIES for l in LETTERS];seen=set(B)
    for p in PARTIES:
        for x in LETTERS:
            for q in PARTIES:
                for y in LETTERS:
                    w=mul(obs(p,x),obs(q,y))
                    if degree(w)==2 and w not in seen: B.append(w);seen.add(w)
    return B

def add(x,y):return (x[0]+y[0],x[1]+y[1])
def times(x,y):return (x[0]*y[0]+2*x[1]*y[1],x[0]*y[1]+x[1]*y[0])
def scale(x,a):return (x[0]*a,x[1]*a)
def scalar(x):return (F(x[0]),F(x[1]))
ZERO=(F(0),F(0))
def sqrt2_interval(digits=90):
    den=10**digits;n=math.isqrt(2*den*den)
    require(n*n<2*den*den<(n+1)*(n+1),'sqrt(2) enclosure invalid')
    return F(n,den),F(n+1,den)
LO,HI=sqrt2_interval()
def enclosure(x):
    a,b=x
    return (a+b*(LO if b>=0 else HI),a+b*(HI if b>=0 else LO))
def abs_upper(x):
    a,b=enclosure(x);return max(abs(a),abs(b))
def decimal_upper(x: F, digits=12) -> str:
    den=10**digits;n=-((-x.numerator*den)//x.denominator)
    return str(n//den)+'.'+str(n%den).zfill(digits)
def no_floats(x):
    if isinstance(x,float):return False
    if isinstance(x,dict):return all(no_floats(z) for z in x.values())
    if isinstance(x,list):return all(no_floats(z) for z in x)
    return True

def verify_affine(data,B,reps):
    ridx={w:i for i,w in enumerate(reps)};rows=set();rt=sp.sqrt(2)
    def moment(w,v): equation({w:1},v)
    def equation(expr,v):
        row=[sp.Integer(0)]*110
        for w,c in expr.items():row[ridx[orbit(w)]]+=c
        rows.add(tuple(row+[sp.expand(v)]))
    moment(ONE,1)
    for p in PARTIES:
        for l,v in [('Z',sp.Rational(1,3)),('X',0),('D',rt/6)]:moment(obs(p,l),v)
    values={('Z','Z'):-sp.Rational(1,3),('Z','X'):0,('X','Z'):0,('Z','D'):-rt/6,('D','Z'):-rt/6,('X','X'):sp.Rational(2,3),('X','D'):rt/3,('D','X'):rt/3,('D','D'):sp.Rational(1,6)}
    for p,q in itertools.combinations(PARTIES,2):
        for x in LETTERS:
            for y in LETTERS:moment(mul(obs(p,x),obs(q,y)),values[x,y])
    for p in PARTIES:
        for x,y,v in [('Z','X',0),('X','Z',0),('Z','D',rt/2),('D','Z',rt/2)]:moment(mul(obs(p,x),obs(p,y)),v)
    for m in B:
        for left in [False,True]:
            expr={m:-1}
            for p in PARTIES:
                w=mul(obs(p,'Z'),m) if left else mul(m,obs(p,'Z'))
                expr[w]=expr.get(w,0)+1
            equation(expr,0)
    b=[sp.Integer(1),rt/6,0,rt/3,sp.Rational(1,6),sp.Rational(2,3),0,rt/2]+[0]*16
    stored=[tuple(row+[rhs]) for row,rhs in zip(data['A'],b)]
    require(all(row in rows for row in stored),'an affine row is not generated by the stated constraints')
    ranks=[sp.Matrix(z).rank() for z in [list(rows),stored,list(rows)+stored]]
    require(ranks==[24,24,24],f'wrong affine ranks {ranks}')
    require(len(rows)==28,f'wrong generated row count {len(rows)}')
    print('Affine constraints: 28 generated quotient rows, 24 stored rows, all ranks 24.')
    return [(F(v.coeff(rt,0)),F(v.coeff(rt))) if isinstance(v,sp.Expr) else (F(v),F(0)) for v in b]

def verify_ideal_kernel(data,B):
    rt=sp.sqrt(2);Q={'Z':sp.diag(1,-1),'X':sp.Matrix([[0,1],[1,0]])};Q['D']=(Q['Z']+Q['X'])/rt
    W=sp.Matrix([0,1,1,0,1,0,0,0]);columns=[]
    for w in B:
        mats=[]
        for seq in w:
            z=sp.eye(2)
            for x in seq:z=z*Q[x]
            mats.append(z)
        columns.append(sp.kronecker_product(*mats)*W)
    V=sp.Matrix.hstack(*columns)
    R=sp.Matrix(data['R_a'])+rt*sp.Matrix(data['R_b']);R=R/data['R_den']
    require(all(sp.expand(x)==0 for x in V*R),'R is not an ideal nullspace basis')
    piv=V.rref()[1];free=[i for i in range(55) if i not in piv]
    require(len(piv)==8 and R[free,:]==sp.eye(47),'R does not have the declared canonical free coordinates')
    print('Ideal action matrix: rank 8; R is the canonical 55 x 47 nullspace basis.')
    return R

def gram_map(data,B,reps):
    n=47; ridx={w:i for i,w in enumerate(reps)}
    word_index=[[ridx[orbit(mul(adj(u),v))] for v in B] for u in B]
    cols=[]
    for r in range(n):cols.append([(i,data['R_a'][i][r],data['R_b'][i][r]) for i in range(55) if data['R_a'][i][r] or data['R_b'][i][r]])
    maps=[]
    for r in range(n):
        for s in range(r,n):
            entries={};factor=1 if r==s else 2
            for i,a,b in cols[r]:
                for j,c,d in cols[s]:
                    k=word_index[i][j];x,y=entries.get(k,(0,0))
                    entries[k]=(x+factor*(a*c+2*b*d),y+factor*(a*d+b*c))
            maps.append({k:v for k,v in entries.items() if v!=(0,0)})
    print('Gram-adjoint map reconstructed independently from ordered words and R.')
    return maps

def integer_product(A,B):
    bt=list(zip(*B))
    return [[sum(a*b for a,b in zip(row,col) if a and b) for col in bt] for row in A]
def transpose(A):return [list(x) for x in zip(*A)]
def positivity(S,Pint,Pden,label):
    # Enclose every S entry in integer intervals of common scale. Subsequent
    # congruences and Gershgorin tests use integer arithmetic only.
    n=len(S);den=10**35;C=[];E=[]
    for row in S:
        crow=[];erow=[]
        for x in row:
            lo,hi=enclosure(x);l=(lo.numerator*den)//lo.denominator;u=-((-hi.numerator*den)//hi.denominator)
            crow.append(l+u);erow.append(u-l)
        C.append(crow);E.append(erow)
    AP=[[abs(x) for x in row] for row in Pint]
    G=integer_product(transpose(Pint),integer_product(C,Pint))
    Err=integer_product(transpose(AP),integer_product(E,AP))
    totalden=2*den*Pden*Pden
    rowsums=[]
    for i in range(n):
        rowsums.append(sum(abs(G[i][j]-(totalden if i==j else 0))+Err[i][j] for j in range(n)))
    bound=F(max(rowsums),totalden)
    require(all(Pint[i][i]!=0 for i in range(n)) and all(Pint[i][j]==0 for i in range(n) for j in range(i)),'congruence matrix must be invertible upper triangular')
    require(bound<F(1,10**6),f'{label} positivity bound does not pass: {bound}')
    print(f'{label}: certified ||P^T M P-I||_infinity < {decimal_upper(bound,12)} < 1/1000000.')
    return bound

