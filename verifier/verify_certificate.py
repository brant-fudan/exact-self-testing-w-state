#!/usr/bin/env python3
"""Full exact verifier for the marginal-W level-2 dual certificate.

The script verifies the certificate over Q(sqrt(2)).  It deliberately avoids
floating-point eigenvalues and Python ``assert`` statements. It loads the
language-neutral JSON certificate distributed with this repository.

Checked items:
  1. no floating-point atoms in exact certificate data;
  2. reconstruction of the 55-word basis and the party/adjoin quotient;
  3. equivalence of the stored affine system to the system generated by the
     marginal constraints, same-party consequences, and localizing equations;
  4. exact reconstruction of the Gram-adjoint map from R and the word basis;
  5. the dual affine identity and b^T lambda = sqrt(2) in Q(sqrt(2));
  6. S >> 0 by rational interval arithmetic and Gershgorin's theorem;
  7. R is the exact ideal W nullspace at level 2;
  8. the vectors for E_Q and E_Q X_Q lie in colspace(R), for Q=A,B,C.
"""
from __future__ import annotations

import itertools
from pathlib import Path
from typing import Any

import sympy as sp

from certificate_io import SQRT2 as s, contains_float_atoms, load_certificate

parties = "ABC"
letters = "ZXD"
perms = list(itertools.permutations(range(3)))
I = ("", "", "")


def check(condition: bool, message: str) -> None:
    if not bool(condition):
        raise ValueError(message)


def reduce_word(st: str) -> str:
    out: list[str] = []
    for ch in st:
        if out and out[-1] == ch:
            out.pop()
        else:
            out.append(ch)
    return "".join(out)


def canon(t: tuple[str, str, str]) -> tuple[str, str, str]:
    return tuple(reduce_word(x) for x in t)  # type: ignore[return-value]


def obs(p: str, l: str) -> tuple[str, str, str]:
    arr = ["", "", ""]
    arr[parties.index(p)] = l
    return tuple(arr)  # type: ignore[return-value]


def mul(u: tuple[str, str, str], v: tuple[str, str, str]) -> tuple[str, str, str]:
    return canon(tuple(u[i] + v[i] for i in range(3)))  # type: ignore[arg-type]


def adj(u: tuple[str, str, str]) -> tuple[str, str, str]:
    return tuple(w[::-1] for w in u)  # type: ignore[return-value]


def deg(u: tuple[str, str, str]) -> int:
    return sum(len(x) for x in u)


def word_str(u: tuple[str, str, str]) -> str:
    out: list[str] = []
    for p, w in zip(parties, u):
        for ch in w:
            out.append(p + ch)
    return "*".join(out) or "I"


def perm_word(w: tuple[str, str, str], perm: tuple[int, int, int]) -> tuple[str, str, str]:
    arr = ["", "", ""]
    for old, new in enumerate(perm):
        arr[new] = w[old]
    return tuple(arr)  # type: ignore[return-value]


def key(w: tuple[str, str, str]) -> tuple[str, str, str]:
    orbit = []
    for perm in perms:
        wp = perm_word(w, perm)
        orbit.append(wp)
        orbit.append(adj(wp))
    return min(orbit, key=lambda x: (deg(x), word_str(x)))


def basis_M2() -> list[tuple[str, str, str]]:
    B = [I]
    seen = set(B)
    for p in parties:
        for l in letters:
            w = obs(p, l)
            check(w not in seen, f"unexpected duplicate one-letter word {w}")
            seen.add(w)
            B.append(w)
    for p1 in parties:
        for l1 in letters:
            for p2 in parties:
                for l2 in letters:
                    w = mul(obs(p1, l1), obs(p2, l2))
                    if deg(w) == 2 and w not in seen:
                        seen.add(w)
                        B.append(w)
    return B


def pair_ab(expr: Any) -> tuple[sp.Rational, sp.Rational]:
    expr = sp.expand(expr)
    a = sp.simplify((expr + expr.xreplace({s: -s})) / 2)
    b = sp.simplify((expr - expr.xreplace({s: -s})) / (2 * s))
    return sp.Rational(a), sp.Rational(b)


def mul_pair(x: tuple[sp.Rational, sp.Rational], y: tuple[sp.Rational, sp.Rational]) -> tuple[sp.Rational, sp.Rational]:
    a, b = x
    c, d = y
    return (a * c + 2 * b * d, a * d + b * c)


def add_pair(x: tuple[sp.Rational, sp.Rational], y: tuple[sp.Rational, sp.Rational]) -> tuple[sp.Rational, sp.Rational]:
    return (x[0] + y[0], x[1] + y[1])


def abs_bound_pair(x: tuple[sp.Rational, sp.Rational], lo: sp.Rational, hi: sp.Rational) -> sp.Rational:
    a, b = x
    vlo = a + b * (lo if b >= 0 else hi)
    vhi = a + b * (hi if b >= 0 else lo)
    return max(abs(vlo), abs(vhi))


def build_constraints(B: list[tuple[str, str, str]]):
    words = {I}
    for u in B:
        for v in B:
            words.add(mul(adj(u), v))
    constraints: list[tuple[dict[tuple[str, str, str], sp.Expr], sp.Expr]] = []

    def add_eq(expr: dict[tuple[str, str, str], sp.Expr], rhs: sp.Expr) -> None:
        expr2 = {k: sp.simplify(v) for k, v in expr.items() if sp.simplify(v) != 0}
        constraints.append((expr2, sp.simplify(rhs)))
        for w in expr2:
            words.add(w)

    def add_moment(w: tuple[str, str, str], val: sp.Expr) -> None:
        add_eq({w: sp.Integer(1)}, val)

    add_moment(I, sp.Integer(1))
    for p in parties:
        add_moment(obs(p, "Z"), sp.Rational(1, 3))
        add_moment(obs(p, "X"), sp.Integer(0))
        add_moment(obs(p, "D"), sp.Rational(1, 3) / s)
    valmap = {
        ("Z", "Z"): -sp.Rational(1, 3),
        ("Z", "X"): sp.Integer(0),
        ("X", "Z"): sp.Integer(0),
        ("Z", "D"): -sp.Rational(1, 3) / s,
        ("D", "Z"): -sp.Rational(1, 3) / s,
        ("X", "X"): sp.Rational(2, 3),
        ("X", "D"): s / 3,
        ("D", "X"): s / 3,
        ("D", "D"): sp.Rational(1, 6),
    }
    for i, p in enumerate(parties):
        for j, q in enumerate(parties):
            if i < j:
                for l1 in letters:
                    for l2 in letters:
                        add_moment(mul(obs(p, l1), obs(q, l2)), valmap[(l1, l2)])
    # Same-party consequences from S_Z |Psi> = |Psi>.
    for p in parties:
        add_moment(mul(obs(p, "Z"), obs(p, "X")), sp.Integer(0))
        add_moment(mul(obs(p, "X"), obs(p, "Z")), sp.Integer(0))
        add_moment(mul(obs(p, "Z"), obs(p, "D")), 1 / s)
        add_moment(mul(obs(p, "D"), obs(p, "Z")), 1 / s)
    Sterms = [obs(p, "Z") for p in parties]
    for m in B:
        expr = {}
        for z in Sterms:
            w = mul(m, z)
            expr[w] = expr.get(w, 0) + 1
        expr[m] = expr.get(m, 0) - 1
        add_eq(expr, sp.Integer(0))
        expr = {}
        for z in Sterms:
            w = mul(z, m)
            expr[w] = expr.get(w, 0) + 1
        expr[m] = expr.get(m, 0) - 1
        add_eq(expr, sp.Integer(0))
    for w in list(words):
        for perm in perms:
            words.add(perm_word(w, perm))
            words.add(adj(perm_word(w, perm)))
    reps = sorted(set(key(w) for w in words), key=lambda w: (deg(w), word_str(w)))
    return constraints, reps


def check_no_floats(cert: dict[str, Any]) -> None:
    for name in ["A", "b", "c", "Bmat", "lam", "S_upper", "R"]:
        check(not contains_float_atoms(cert[name]), f"floating-point atom found in {name}")
    print("No floating-point atoms in exact certificate entries: OK")


def check_basis_and_constraints(cert: dict[str, Any]) -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    B = basis_M2()
    check(B == cert["B"], "stored basis does not match reconstructed M2 basis")
    constraints, reps = build_constraints(B)
    check(reps == cert["reps"], "stored quotient representatives do not match reconstructed reps")
    ridx = {w: i for i, w in enumerate(reps)}
    print(f"Basis and quotient moments: OK ({len(B)} words, {len(reps)} orbit variables)")

    rows = []
    for expr, rhs in constraints:
        row = [sp.Integer(0)] * len(reps)
        for w, coeff in expr.items():
            row[ridx[key(w)]] += coeff
        rows.append([sp.simplify(x) for x in row] + [sp.simplify(rhs)])
    unique_rows = sorted({tuple(r) for r in rows})

    A, bvec = cert["A"], cert["b"]
    stored_rows = []
    for i in range(A.rows):
        stored_rows.append([sp.simplify(A[i, j]) for j in range(A.cols)] + [sp.simplify(bvec[i])])

    rowset = set(tuple(r) for r in unique_rows)
    for i, row in enumerate(stored_rows):
        check(tuple(row) in rowset, f"stored affine row {i} is not generated by the stated constraints")

    # The stored rows may be a row-reduced subsystem.  Check equality of spans of
    # augmented rows, which is what the affine identity uses.
    rank_stored = sp.Matrix(stored_rows).rank()
    rank_generated = sp.Matrix(unique_rows).rank()
    rank_combined = sp.Matrix(stored_rows + [list(r) for r in unique_rows]).rank()
    check(rank_stored == rank_generated == rank_combined,
          f"affine spans differ: stored={rank_stored}, generated={rank_generated}, combined={rank_combined}")
    print(f"Affine system: OK ({A.rows} stored rows span {len(unique_rows)} generated quotient rows; rank {rank_stored})")

    # Objective c = symmetrized same-party D X + X D.
    c = [sp.Integer(0)] * len(reps)
    c[ridx[key(mul(obs("B", "D"), obs("B", "X")))]] += 1
    c[ridx[key(mul(obs("B", "X"), obs("B", "D")))]] += 1
    check(sp.Matrix(c) == cert["c"], "objective vector mismatch")
    print("Objective vector: OK")
    return B, reps


def check_Bmat(cert: dict[str, Any], B: list[tuple[str, str, str]], reps: list[tuple[str, str, str]]) -> None:
    R = cert["R"]
    pairs = cert["pairs"]
    Bmat = cert["Bmat"]
    ridx = {w: i for i, w in enumerate(reps)}
    pair_rep: list[list[int]] = []
    for i, u in enumerate(B):
        row = []
        for j, v in enumerate(B):
            row.append(ridx[key(mul(adj(u), v))])
        pair_rep.append(row)

    # Sparse nonzero lists for columns of R make this independent reconstruction fast.
    Rcols = []
    for col in range(R.cols):
        Rcols.append([(row, R[row, col]) for row in range(R.rows) if R[row, col] != 0])

    for col, (a, b) in enumerate(pairs):
        coeffs: dict[int, sp.Expr] = {}
        for j, Rja in Rcols[a]:
            for i, Rib in Rcols[b]:
                k = pair_rep[i][j]
                coeffs[k] = coeffs.get(k, 0) + Rja * Rib
        if a != b:
            for j, Rjb in Rcols[b]:
                for i, Ria in Rcols[a]:
                    k = pair_rep[i][j]
                    coeffs[k] = coeffs.get(k, 0) + Rjb * Ria
        for k, val in coeffs.items():
            check(sp.simplify(val - Bmat[k, col]) == 0, f"Bmat mismatch at row {k}, column {col}")
        # Check stored nonzeros outside coeffs are absent.  This is cheap because Bmat is short in rows.
        for k in range(Bmat.rows):
            if k not in coeffs:
                check(Bmat[k, col] == 0, f"Bmat has spurious entry at row {k}, column {col}")
    print("Gram-adjoint map Bmat rebuilt exactly from R and basis: OK")


def check_dual_identity(cert: dict[str, Any]) -> None:
    A, bvec, cvec, Bmat = cert["A"], cert["b"], cert["c"], cert["Bmat"]
    x = list(cert["lam"]) + list(cert["S_upper"])
    xp = [pair_ab(v) for v in x]
    r = len(cert["lam"])
    for row in range(cvec.rows):
        acc = (sp.Rational(0), sp.Rational(0))
        for j in range(r):
            coeff = A[j, row]
            if coeff:
                acc = add_pair(acc, mul_pair(pair_ab(coeff), xp[j]))
        for j in range(len(cert["S_upper"])):
            coeff = Bmat[row, j]
            if coeff:
                acc = add_pair(acc, mul_pair(pair_ab(coeff), xp[r + j]))
        rhs = pair_ab(cvec[row])
        check(acc == rhs, f"affine identity failed in quotient row {row}: {acc} != {rhs}")
    acc = (sp.Rational(0), sp.Rational(0))
    for j in range(r):
        if bvec[j]:
            acc = add_pair(acc, mul_pair(pair_ab(bvec[j]), xp[j]))
    check(acc == (sp.Rational(0), sp.Rational(1)), f"objective failed: {acc} != sqrt(2)")
    print("Affine dual identity and objective b^T lambda = sqrt(2): exact OK")


def check_positive_definiteness(cert: dict[str, Any]) -> sp.Rational:
    qbound = 10**80
    plow = int(sp.integer_nthroot(2 * qbound * qbound, 2)[0])
    sqrt2_lower = sp.Rational(plow, qbound)
    sqrt2_upper = sp.Rational(plow + 1, qbound)
    check(sqrt2_lower**2 < 2 and sqrt2_upper**2 > 2, "invalid rational enclosure for sqrt(2)")
    m = cert["R"].cols
    S0 = sp.zeros(m, m)
    S1 = sp.zeros(m, m)
    for val, (i, j) in zip(cert["S_upper"], cert["pairs"]):
        a, b = pair_ab(val)
        S0[i, j] = S0[j, i] = a
        S1[i, j] = S1[j, i] = b
    P = sp.Matrix([[sp.Rational(v, cert["P_den"]) for v in row] for row in cert["P_int"]])
    check(P.rows == m and P.cols == m, "PSD congruence matrix P has wrong shape")
    for i in range(m):
        check(P[i, i] != 0, f"P diagonal entry {i} is zero")
        for j in range(i):
            check(P[i, j] == 0, f"P is not upper triangular at ({i},{j})")
    T0 = P.T * S0 * P
    T1 = P.T * S1 * P
    max_row = sp.Rational(0)
    for i in range(m):
        row_sum = sp.Rational(0)
        for j in range(m):
            a = T0[i, j] - (sp.Rational(1) if i == j else sp.Rational(0))
            b = T1[i, j]
            row_sum += abs_bound_pair((a, b), sqrt2_lower, sqrt2_upper)
        if row_sum > max_row:
            max_row = row_sum
    check(max_row < 1, f"PSD Gershgorin bound failed: row bound {max_row} >= 1")
    print(f"Gram matrix S >> 0 by exact Gershgorin bound: OK; row bound = {max_row}")
    return max_row


def check_nullspace_and_relations(cert: dict[str, Any], B: list[tuple[str, str, str]]) -> None:
    R = cert["R"]
    Z = sp.Matrix([[1, 0], [0, -1]])
    X = sp.Matrix([[0, 1], [1, 0]])
    D = (Z + X) / s
    I2 = sp.eye(2)
    matmap = {"Z": Z, "X": X, "D": D}

    def kron3(A, B, C):
        return sp.kronecker_product(A, B, C)

    def op_for_word(w: tuple[str, str, str]) -> sp.Matrix:
        ops = []
        for local in w:
            M = I2
            for ch in local:
                M = M * matmap[ch]
            ops.append(M)
        return kron3(*ops)

    W = sp.zeros(8, 1)
    W[1] = 1 / sp.sqrt(3)  # |001>
    W[2] = 1 / sp.sqrt(3)  # |010>
    W[4] = 1 / sp.sqrt(3)  # |100>
    V = sp.zeros(8, len(B))
    for j, w in enumerate(B):
        V[:, j] = op_for_word(w) * W
    check(V.rank() == 8, f"unexpected ideal word-vector rank {V.rank()}")
    check(R.rank() == R.cols, f"R is not full column rank: {R.rank()} != {R.cols}")
    check(sp.simplify(V * R) == sp.zeros(8, R.cols), "R is not in ideal nullspace")
    print(f"Ideal W nullspace: exact OK (rank V = {V.rank()}, rank R = {R.rank()})")

    idx = {w: i for i, w in enumerate(B)}

    def vec(terms: dict[tuple[str, str, str], sp.Expr]) -> sp.Matrix:
        v = sp.zeros(len(B), 1)
        for w, coeff in terms.items():
            v[idx[w]] += coeff
        return v

    witnesses = cert["target_witnesses"]
    for p in parties:
        e = vec({obs(p, "D"): s, obs(p, "Z"): -1, obs(p, "X"): -1})
        ex = vec({mul(obs(p, "D"), obs(p, "X")): s,
                  mul(obs(p, "Z"), obs(p, "X")): -1,
                  I: -1})
        key_e = f"E_{p}"
        key_ex = f"E_{p}X_{p}"
        check(key_e in witnesses, f"missing target witness {key_e}")
        check(key_ex in witnesses, f"missing target witness {key_ex}")
        witness_e = sp.Matrix(witnesses[key_e])
        witness_ex = sp.Matrix(witnesses[key_ex])
        check(
            witness_e.shape == (R.cols, 1),
            f"witness {key_e} has wrong shape",
        )
        check(
            witness_ex.shape == (R.cols, 1),
            f"witness {key_ex} has wrong shape",
        )
        check(
            sp.simplify(R * witness_e - e) == sp.zeros(R.rows, 1),
            f"witness {key_e} does not satisfy Rw=E",
        )
        check(
            sp.simplify(R * witness_ex - ex) == sp.zeros(R.rows, 1),
            f"witness {key_ex} does not satisfy Rw=EX",
        )
    print("E_Q and E_Q X_Q target vectors lie in colspace(R): exact OK")


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    cert_path = root / "certificate" / "w_exact_certificate.json"
    check(cert_path.is_file(), f"certificate not found: {cert_path}")
    cert = load_certificate(cert_path)
    print(f"Loaded certificate: {cert_path}")

    check_no_floats(cert)
    B, reps = check_basis_and_constraints(cert)
    check_Bmat(cert, B, reps)
    check_dual_identity(cert)
    check_positive_definiteness(cert)
    check_nullspace_and_relations(cert, B)
    print("FULL CERTIFICATE VERIFIED.")


if __name__ == "__main__":
    main()
